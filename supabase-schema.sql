create extension if not exists pgcrypto;

create table if not exists public.clients (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  phone text,
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists public.transactions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  date date not null default current_date,
  type text not null check (type in ('entrada','saida')),
  description text not null,
  category text not null,
  amount numeric(12,2) not null check (amount > 0),
  payment_method text,
  status text not null default 'pago' check (status in ('pago','pendente')),
  created_at timestamptz not null default now()
);

create table if not exists public.service_orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  order_number bigint generated by default as identity,
  client_id uuid not null references public.clients(id) on delete restrict,
  device text not null,
  problem text not null,
  service text,
  price numeric(12,2) not null default 0 check (price >= 0),
  paid numeric(12,2) not null default 0 check (paid >= 0),
  status text not null default 'Recebido',
  created_at timestamptz not null default now(),
  constraint paid_not_over_price check (paid <= price)
);

alter table public.clients enable row level security;
alter table public.transactions enable row level security;
alter table public.service_orders enable row level security;

drop policy if exists "owner clients" on public.clients;
create policy "owner clients" on public.clients for all to authenticated
using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "owner transactions" on public.transactions;
create policy "owner transactions" on public.transactions for all to authenticated
using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "owner orders" on public.service_orders;
create policy "owner orders" on public.service_orders for all to authenticated
using (auth.uid() = user_id) with check (auth.uid() = user_id);

create index if not exists transactions_user_date_idx on public.transactions(user_id,date desc);
create index if not exists clients_user_name_idx on public.clients(user_id,name);
create index if not exists orders_user_created_idx on public.service_orders(user_id,created_at desc);
